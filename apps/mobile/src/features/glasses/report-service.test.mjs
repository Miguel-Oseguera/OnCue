import assert from "node:assert/strict";
import test from "node:test";
import { createReportService, deliverReport } from "./report-service.ts";

const testImage = new Blob(["test jpeg"], { type: "image/jpeg" });
const createService = (request, formFactory = form) =>
  createReportService(request, () => testImage, formFactory);
const photo = {
  id: "capture-1",
  uri: "file:///captures/capture-1.jpg",
  capturedAt: "2026-10-25T12:00:00Z",
  source: "voice",
  deviceId: "glasses",
  ownerId: "user-1",
  description: "  Projector in room 204 is broken.  ",
  delivery: "pending",
};
function form() {
  return {
    fields: [],
    append(key, value, name) {
      this.fields.push(name ? [key, value, name] : [key, value]);
    },
  };
}
test("sends image and trimmed description in one authenticated API request with a longer AI timeout", async () => {
  const body = form();
  let calls = 0;
  const service = createService(
    async (path, init, options) => {
      calls++;
      assert.equal(path, "/api/ai");
      assert.equal(init.method, "POST");
      assert.equal(init.body, body);
      assert.equal(init.headers, undefined); // multipart boundary must be generated by native fetch
      assert.deepEqual(options, { timeoutMs: 120000 });
      assert.deepEqual(body.fields, [
        ["text", "Projector in room 204 is broken."],
        ["source", "glasses"],
        ["images", testImage, "capture-1.jpg"],
      ]);
      return {
        processed: true,
        analysis: {},
        tasks: [{ id: "task-1" }, { id: "task-1" }],
      };
    },
    () => body,
  );
  assert.deepEqual(await service.submit(photo), { taskIds: ["task-1"] });
  assert.equal(calls, 1);
});
test("does not send a report without a description or a local photo", async () => {
  const service = createService(async () => {
    assert.fail("must not contact backend");
  }, form);
  await assert.rejects(
    service.submit({ ...photo, description: " " }),
    /description/,
  );
  await assert.rejects(
    service.submit({ ...photo, uri: "https://example.com/a.jpg" }),
    /photo/,
  );
  await assert.rejects(
    service.submit({ ...photo, description: "x".repeat(10001) }),
    /10,000/,
  );
});
test("accepts processed reports with no tasks and rejects unconfirmed or malformed responses", async () => {
  const run = (response) =>
    createService(async () => response, form).submit(photo);
  assert.deepEqual(await run({ processed: true, tasks: [] }), { taskIds: [] });
  for (const response of [
    null,
    {},
    { processed: false, tasks: [] },
    { processed: true, tasks: [{}] },
  ])
    await assert.rejects(run(response));
});
test("durably marks uploading before POST and marks sent only after confirmation", async () => {
  const events = [];
  const result = await deliverReport(photo, {
    mark: async (update) => {
      events.push(update.status);
    },
    submit: async () => {
      events.push("post");
      return { taskIds: ["task-1"] };
    },
  });
  assert.equal(result, true);
  assert.deepEqual(events, ["uploading", "post", "sent"]);
});
test("does not POST if the durable claim cannot be saved", async () => {
  await assert.rejects(
    deliverReport(photo, {
      mark: async () => {
        throw new Error("disk full");
      },
      submit: async () => {
        assert.fail("must not POST");
      },
    }),
    /disk full/,
  );
});
test("a timed-out POST is attempted once and requires explicit retry", async () => {
  let calls = 0;
  const updates = [];
  assert.equal(
    await deliverReport(photo, {
      mark: async (update) => updates.push(update),
      submit: async () => {
        calls++;
        throw new Error("timeout");
      },
    }),
    false,
  );
  assert.equal(calls, 1);
  assert.deepEqual(
    updates.map((value) => value.status),
    ["uploading", "uncertain"],
  );
  assert.match(updates[1].message, /duplicates/);
});
test("failed local confirmation after successful backend processing is not resubmitted", async () => {
  let posts = 0;
  const updates = [];
  await deliverReport(photo, {
    mark: async (update) => {
      updates.push(update.status);
      if (update.status === "sent") throw new Error("disk full");
    },
    submit: async () => {
      posts++;
      return { taskIds: [] };
    },
  });
  assert.equal(posts, 1);
  assert.deepEqual(updates, ["uploading", "sent", "uncertain"]);
});
